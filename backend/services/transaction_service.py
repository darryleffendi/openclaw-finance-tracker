from datetime import datetime

from backend.db import get_connection
from backend.repositories import account_bucket_repository as bucket_repo
from backend.repositories import account_repository as account_repo
from backend.repositories import transaction_repository as transaction_repo
from backend.services.distribution_service import distribute_within, transfer_within


def _internal_column(row):
    """Bucket column an auto-distribution row was recorded in."""
    prefix = "settle" if row["subcategory"] == transaction_repo.SETTLEMENT_SUBCATEGORY else "auto_dist"
    return f"{prefix}_{'in' if row['type'] == 'income' else 'out'}"


def insert_transaction(
    amount: float,
    type: str,
    category: str,
    subcategory: str = None,
    note: str = None,
    date: str = None,
):
    if date is None:
        date = datetime.now().strftime("%Y-%m-%d")
    year_month = date[:7]

    with get_connection() as conn:
        txn_id = transaction_repo.insert(
            conn,
            amount=amount,
            type=type,
            category=category,
            subcategory=subcategory,
            note=note,
            date=date,
        )

        acct = account_repo.get_by_slug(conn, category)
        distributed = []
        if acct:
            if type == "income":
                bucket_repo.apply_delta(conn, category, year_month, income=amount)
            else:
                bucket_repo.apply_delta(conn, category, year_month, expense=amount)
            if category == "salary" and type == "income":
                distributed = distribute_within(conn, "salary", amount, date, parent_id=txn_id)
            elif category == "other_income" and type == "income":
                distributed = transfer_within(conn, "other_income", "savings", amount, date, parent_id=txn_id)

        conn.commit()
        return txn_id, distributed


def insert_transfer(conn, source_account, target_account, amount, date, subcategory=None):
    """
    Write a transfer pair on the caller's connection (no commit): an expense on
    the source (parent) and a matching income on the target (child). Rows tagged
    with the settlement subcategory go to settle_* bucket columns, others to
    auto_dist_*. Returns (source_id, target_id).
    """
    year_month = date[:7]
    prefix = "settle" if subcategory == transaction_repo.SETTLEMENT_SUBCATEGORY else "auto_dist"
    source_id = transaction_repo.insert(
        conn,
        amount=amount,
        type="expense",
        category=source_account,
        subcategory=subcategory,
        note=transaction_repo.AUTO_DIST_NOTE,
        date=date,
    )
    bucket_repo.apply_delta(conn, source_account, year_month, **{f"{prefix}_out": amount})
    target_id = transaction_repo.insert(
        conn,
        amount=amount,
        type="income",
        category=target_account,
        subcategory=subcategory,
        note=transaction_repo.AUTO_DIST_NOTE,
        date=date,
        parent_id=source_id,
    )
    bucket_repo.apply_delta(conn, target_account, year_month, **{f"{prefix}_in": amount})
    return source_id, target_id


def transfer(source_account: str, target_account: str, amount: float, date: str = None):
    """
    Move money from source_account to target_account. Writes an expense on the
    source (the parent row) and a matching income on the target (its child),
    both as auto-distribution rows: balances move, summary income/expense don't.
    Deleting the source row deletes the pair.
    """
    if source_account == target_account:
        raise ValueError("Source and target accounts must differ")
    if amount <= 0:
        raise ValueError("Amount must be positive")
    if date is None:
        date = datetime.now().strftime("%Y-%m-%d")

    with get_connection() as conn:
        for slug in (source_account, target_account):
            if account_repo.get_by_slug(conn, slug) is None:
                raise ValueError(f"Account not found: {slug}")

        source_id, target_id = insert_transfer(conn, source_account, target_account, amount, date)
        conn.commit()
        return {"id": source_id, "target_id": target_id}


def delete_transaction(txn_id: int) -> bool:
    with get_connection() as conn:
        row = transaction_repo.get_by_id(conn, txn_id)
        if row is None:
            return False

        # Cascade-delete auto-distribution rows generated by this transaction.
        # Reverses both the target income rows AND the source expense mirror row.
        for dr in transaction_repo.find_children(conn, txn_id):
            dr_month = dr["date"][:7]
            transaction_repo.delete(conn, dr["id"])
            bucket_repo.apply_delta(conn, dr["category"], dr_month, **{_internal_column(dr): -dr["amount"]})

        # Reverse the main row's bucket impact. Skip if this row is itself an
        # auto-distribution (handled in the cascade above to avoid double-reversal).
        if row["parent_id"] is None:
            row_month = row["date"][:7]
            if row["note"] == transaction_repo.AUTO_DIST_NOTE:
                # Transfer source row: recorded as auto-distribution out, not expense.
                bucket_repo.apply_delta(conn, row["category"], row_month, **{_internal_column(row): -row["amount"]})
            elif row["type"] == "income":
                bucket_repo.apply_delta(conn, row["category"], row_month, income=-row["amount"])
            else:
                bucket_repo.apply_delta(conn, row["category"], row_month, expense=-row["amount"])

        transaction_repo.delete(conn, txn_id)
        conn.commit()
        return True


def update_transaction(txn_id: int, amount: float = None, note: str = None, date: str = None):
    """
    Edit a transaction's amount, note and/or date. Type and category are immutable.

    Auto-distribution rows (parent_id set) cannot be edited directly — edit
    the parent salary row instead.

    For salary / other_income income rows: an amount or date change uses
    delete-and-reinsert to correctly re-run the cascade at the (possibly new) date. The returned
    new_id replaces the old id.

    A date change that crosses a month boundary moves the transaction's bucket
    impact from the old month to the new month, since buckets are month-keyed.

    Returns a dict with the result including new_id (may equal txn_id for
    non-salary edits).
    """
    if amount is None and note is None and date is None:
        raise ValueError("Supply at least one of: amount, note, date")

    if date is not None:
        try:
            datetime.strptime(date, "%Y-%m-%d")
        except ValueError:
            raise ValueError("Date must be in YYYY-MM-DD format")

    with get_connection() as conn:
        row = transaction_repo.get_by_id(conn, txn_id)
        if row is None:
            return None

        if row["parent_id"] is not None:
            raise ValueError("Cannot edit auto-distribution rows directly. Edit the parent salary transaction instead.")
        if row["note"] == transaction_repo.AUTO_DIST_NOTE:
            raise ValueError("Cannot edit a transfer. Delete it and create a new one.")

    new_date = date if date is not None else row["date"]
    amount_changed = amount is not None and amount != row["amount"]
    date_changed = date is not None and date != row["date"]
    month_changed = date_changed and new_date[:7] != row["date"][:7]

    # Salary / other_income amount or date change: cascade-delete old + reinsert at new date
    if (amount_changed or date_changed) and row["category"] in ("salary", "other_income") and row["type"] == "income":
        delete_transaction(txn_id)
        new_id, distributed = insert_transaction(
            amount=amount if amount is not None else row["amount"],
            type=row["type"],
            category=row["category"],
            subcategory=row["subcategory"],
            note=note if note is not None else row["note"],
            date=new_date,
        )
        return {"new_id": new_id, "old_id": txn_id, "salary_redistributed": True, "distributions": distributed}

    # Non-salary or note-only edit: in-place update
    with get_connection() as conn:
        old_month = row["date"][:7]
        new_month = new_date[:7]
        old_amt = row["amount"]
        new_amt = amount if amount is not None else old_amt

        # Reverse the full old impact from the old month and apply the full new
        # impact to the new month. When only the amount changed within the same
        # month this nets to (new_amt - old_amt) on that month's bucket.
        if amount_changed or month_changed:
            if row["type"] == "income":
                bucket_repo.apply_delta(conn, row["category"], old_month, income=-old_amt)
                bucket_repo.apply_delta(conn, row["category"], new_month, income=new_amt)
            else:
                bucket_repo.apply_delta(conn, row["category"], old_month, expense=-old_amt)
                bucket_repo.apply_delta(conn, row["category"], new_month, expense=new_amt)

        if amount_changed:
            conn.execute("UPDATE transactions SET amount = ? WHERE id = ?", (new_amt, txn_id))

        if date_changed:
            conn.execute("UPDATE transactions SET date = ? WHERE id = ?", (new_date, txn_id))

        if note is not None:
            transaction_repo.update_note(conn, txn_id, note)

        conn.commit()

    return {"new_id": txn_id, "old_id": txn_id, "salary_redistributed": False}
